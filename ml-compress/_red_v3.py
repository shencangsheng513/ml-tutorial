def ver_rank(q):                     # 文件名尾的 _v<N>；无后缀 = v1 时代，记 0
    _head, sep, tail = q.rsplit(".json", 1)[0].rpartition("_v")
    return int(tail) if sep and tail.isdigit() else 0


