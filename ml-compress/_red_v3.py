# ---------- ⑮ 债句指针（第二十八发：把上一发记成"新欠"的那根会漂的指针变成守卫） ----------
# 形状：档案里「<某本账>.json 的 limitations 第 N 条（『引文』…）」——文件名 + 序号 + 引文三件套齐了才算**可核指针**。
